#!/bin/bash
# Builds the portable prebuilt Nebulae binary prebuilt/armv7/libpearls.so,
# for installing Pearls from a USB stick without compiling on the module.
#
# Portability, checked by this script:
# - Csound: compiled against the Csound 6.09 headers. The plugin only uses
#   ABI elements that are identical from Csound 6.08 to 6.18 on armhf
#   (OPDS/OENTRY/INSDS layout, plugin API 4.0, the CSOUND functions it calls).
# - System libraries: needs only glibc 2.17 (2012) and libstdc++ symbols from GCC 4.x
#   (-fno-sized-deallocation, and the pre-C++11 std::string ABI), so it loads
#   on the 2017-2019 Arch Linux ARM
#   images of the Nebulae. Recent armhf toolchains default to a 64-bit
#   time_t (glibc 2.34+); the classic 32-bit ABI of those images is used.
#
# Requires an arm-linux-gnueabihf cross compiler (Debian/Ubuntu package
# g++-arm-linux-gnueabihf) and git.

set -e
HERE=$(cd "$(dirname "$0")/.." && pwd)
CXX=${CXX:-arm-linux-gnueabihf-g++}
CROSS=${CXX%g++}
BUILD="$HERE/build-prebuilt"
HEADERS="$BUILD/csound-6.09.1"
OUT="$HERE/prebuilt/armv7"

if [ ! -f "$HEADERS/include/csdl.h" ]; then
    rm -rf "$HEADERS"
    git clone -q --depth 1 --branch 6.09.1 --filter=blob:none --sparse \
        https://github.com/csound/csound.git "$HEADERS"
    git -C "$HEADERS" sparse-checkout set --no-cone /include/
fi
# Headers normally generated by Csound's CMake build.
if [ ! -f "$HEADERS/include/version.h" ]; then
    sed -e 's/${CS_VERSION}/6/; s/${CS_SUBVER}/09/; s/${CS_PATCHLEVEL}/1/' \
        "$HEADERS/include/version.h.in" > "$HEADERS/include/version.h"
fi
echo "#define USE_DOUBLE 1" > "$HEADERS/include/float-version.h"

make -C "$HERE" -j4 BUILD="$BUILD" CXX="$CXX" \
    CSOUND_INCLUDE="$HEADERS/include" CSOUND_DOUBLE=1 \
    CXXFLAGS="-O2 -fno-sized-deallocation -D_GLIBCXX_USE_CXX11_ABI=0 -U_TIME_BITS -U_FILE_OFFSET_BITS" \
    "$BUILD/libpearls.so"

mkdir -p "$OUT"
"${CROSS}strip" -o "$OUT/libpearls.so" "$BUILD/libpearls.so"

# Refuse binaries that need newer system libraries than the Nebulae has.
versions=$("${CROSS}objdump" -T "$OUT/libpearls.so" |
    grep -oE "(GLIBC|GLIBCXX|CXXABI)_[0-9.]+" | sort -u)
echo "Symbol versions required:" $versions
for v in $versions; do
    case "$v" in
        GLIBC_2.4|GLIBC_2.17|GLIBCXX_3.4|CXXABI_1.3) ;;
        *) echo "error: $v is too recent for the Nebulae"; rm -f "$OUT/libpearls.so"; exit 1 ;;
    esac
done

{
    echo "libpearls.so for Nebulae v2 (armv7 hard-float, Csound 6 double)"
    echo "source commit: $(git -C "$HERE" rev-parse --short HEAD 2>/dev/null || echo unknown)"
    echo "compiler: $($CXX --version | head -n 1)"
    echo "csound headers: 6.09.1"
    echo "requires:" $versions
    echo "sha256: $(sha256sum "$OUT/libpearls.so" | cut -d ' ' -f 1)"
} > "$OUT/BUILD_INFO.txt"
cat "$OUT/BUILD_INFO.txt"
